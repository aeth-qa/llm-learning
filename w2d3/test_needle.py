# test_needle.py
from agent import SimpleAgent

agent = SimpleAgent()
agent.reset()

# Заполнитель: 5000 повторов ~ 40K токенов на "до" + "после"
filler = "Это очень длинный тестовый текст на русском языке. " * 50000

# Иголка (уникальная фраза)
needle = "\n\nВАЖНАЯ ИНФОРМАЦИЯ: секретный код — БАНАН-42-КИВИ.\n\n"

# Зашиваем иголку в середину
haystack = filler + needle + filler

question = (
    "Ниже очень длинный текст. В нём где-то спрятан секретный код. "
    "Найди его и назови. Если не находишь — честно скажи, что не видишь.\n\n"
    + haystack
)

print(f"Размер запроса: ~{len(question)} символов\n")
answer = agent.run(question)
print(f"\nОтвет модели: {answer}")

if "БАНАН" in answer.upper() or "КИВИ" in answer.upper():
    print("\n✅ Модель нашла иголку — она действительно читает весь контекст!")
else:
    print("\n❌ Модель не нашла иголку — либо контекст обрезан,")
    print("   либо внимание модели не дотягивается до середины.")